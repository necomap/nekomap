-- NekoMap ボランティア機能の一本化（掲示板→専用ページのみに）
-- 実行方法: Supabase ダッシュボード → SQL Editor に貼り付けて実行（任意）
--
-- 背景: 掲示板（posts）の「🙋 ボランティア」カテゴリを廃止し、
--   ボランティア募集は /volunteer 専用ページに一本化した。
--   これは新規投稿の選択肢からカテゴリを消しただけなので、
--   もし過去に category='volunteer' で投稿された掲示板の投稿が
--   残っている場合、そのままだとカテゴリ表示が「💬 一般」に
--   フォールバックする。気にならなければ実行しなくてもよいが、
--   実行すると表示上も一般カテゴリに揃う（データが無ければ何も起きない）。
-- ============================================================

update public.posts set category = 'general' where category = 'volunteer';

-- 確認: 対象件数（実行前に確認したい場合は上のupdateをコメントアウトしてこちらだけ実行）
select count(*) as volunteer_category_posts from public.posts where category = 'volunteer';
